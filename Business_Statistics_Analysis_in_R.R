#################### Άσκηση 1 #####################
# Έλεγχος υπόθεσης για έναν πληθυσμιακό μέσο
# Η επιχείρηση ισχυρίζεται ότι ο μέσος χρόνος εξυπηρέτησης είναι > 10 λεπτά
# Χρήση t-test, επειδή η πληθυσμιακή τυπική απόκλιση είναι άγνωστη

# Ορισμός των απαραίτητων μεταβλητών
sample_size <- 40
sample_mean <- 10.8
sample_sd <- 2.5
null_mean_value <- 10
a <- 0.05

# HO-> μ=10 και H1-> μ>10

# Υπολογισμός του στατιστικού ελέγχου t
t_stat <- (sample_mean - null_mean_value) / (sample_sd / sqrt(sample_size))

# Βαθμοί ελευθερίας
df <- sample_size - 1

# Υπολογισμός p-value
p_value <- pt(t_stat, df, lower.tail = FALSE)

# Έλεγχος της εναλλακτικής υπόθεσης
print(p_value < a)

# Εκτύπωση αποτελεσμάτων
print(paste0("Το t-statistic είναι: ", t_stat))
print(paste0("Το p-value είναι: ", p_value))

if (p_value < a) {
  print("Απορρίπτουμε τη μηδενική υπόθεση H0.")
  print("Υπάρχουν επαρκή στοιχεία ότι ο μέσος χρόνος εξυπηρέτησης είναι μεγαλύτερος από 10 λεπτά.")
} else {
  print("Δεν απορρίπτουμε τη μηδενική υπόθεση H0.")
  print("Δεν υπάρχουν επαρκή στοιχεία ότι ο μέσος χρόνος εξυπηρέτησης είναι μεγαλύτερος από 10 λεπτά.")
}



#################### Γράφημα απορριπτικής περιοχής για δεξιόπλευρο t-test ####################

# Υπολογισμός κρίσιμης τιμής. Είναι το όριο από το οποίο αρχίζει η απορριπτική περιοχή
critical_value <- qt(1 - a, df)

# Δημιουργία τιμών στον άξονα x για την t-κατανομή
x_values <- seq(-3, 3, length = 1000)   #Φτιάχνουμε 1000 αριθμούς από το -3 μέχρι το 3

# Υπολογισμός τιμών πυκνότητας πιθανότητας για κάθε x
y_values <- dt(x_values, df)    #Υπολογίζει το ύψος της t-κατανομής για κάθε τιμή του x_values

# Σχεδίαση της t-κατανομής
plot(x_values, y_values,
     type = "l",    #Σημαίνει line ώστε να σχεδιαστεί γραμμή
     main = "Απορριπτική περιοχή για δεξιόπλευρο t-test",
     xlab = "Τιμές t",
     ylab = "Πυκνότητα πιθανότητας")

# Επιλογή των τιμών που ανήκουν στην απορριπτική περιοχή
rejection_region <- x_values[x_values >= critical_value]

# Υπολογισμός της πυκνότητας πιθανότητας στην απορριπτική περιοχή
rejection_density <- dt(rejection_region, df)

# Σκίαση της απορριπτικής περιοχής
polygon(c(critical_value, rejection_region, max(rejection_region)),    #Δίνει τις τιμές στον άξονα x
        c(0, rejection_density, 0),    #Δίνει τα αντίστοιχα ύψη στον άξονα y
        col = "lightgray")

# Κάθετη γραμμή στην κρίσιμη τιμή
abline(v = critical_value, lty = 2)

# Κάθετη γραμμή στο υπολογισμένο t-statistic
abline(v = t_stat, lty = 2)





#################### Άσκηση 2 ####################
# Υπολογισμός 95% διαστήματος εμπιστοσύνης για πληθυσμιακή διακύμανση
