# Δημιουργία τιμών για τον άξονα x
x_values <- seq(0, 30, length = 1000)
#Η seq() δημιουργεί μία ακολουθία 1000 αριθμών από το 0 έως το 30

# Υπολογισμός τιμών πυκνότητας της F κατανομής
y_values <- df(x_values, k - 1, n - k)
#Για κάθε τιμή του x_values, η df() υπολογίζει το ύψος της καμπύλης F

# Σχεδίαση της F κατανομής
plot(x_values, y_values,
     type = "l",
     main = "Απορριπτική περιοχή για ANOVA",
     xlab = "Τιμή F",
     ylab = "Πυκνότητα πιθανότητας",
     ylim = c(0, 0.15))  #Καθορίζει τα όρια του κατακόρυφου άξονα y

# Επιλογή των τιμών της απορριπτικής περιοχής
rejection_region <- x_values[x_values >= f_cr]

# Υπολογισμός πυκνότητας στην απορριπτική περιοχή
rejection_density <- df(rejection_region, k - 1, n - k)

# Σκίαση απορριπτικής περιοχής
polygon(c(f_cr, rejection_region, max(rejection_region)),
        #Μας δίνει τις x συντεταγμένες του πολύγωνου
        #Η max(rejection_region είναι το τελευταίο σημείο στα δεξιά
        c(0, rejection_density, 0),
        #Μας δίνει τις y συντεταγμένες του πολύγωνου
        col = "lightgray")


# Κάθετη γραμμή στην κρίσιμη τιμή F
abline(v = f_cr, lty = 2)

# Κείμενο δίπλα στην κρίσιμη τιμή F
text(f_cr + 0.2, 0.13, "Κρίσιμη τιμή F", pos = 4)

# Κάθετη γραμμή στο υπολογισμένο F-statistic
abline(v = F_stat, lty = 2)

# Κείμενο δίπλα στο F-statistic
text(F_stat + 0.2, 0.13, "F-statistic", pos = 4)

