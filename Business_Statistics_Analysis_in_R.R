#################### Άσκηση 4 ####################
# Υπολογισμός 99% διαστήματος εμπιστοσύνης για τη διαφορά δύο πληθυσμιακών μέσων
# Σύγκριση μέσης ημερήσιας απόδοσης δύο καταστημάτων
# Χρήση διαστήματος εμπιστοσύνης για μ1 - μ2
# Χρειάζεται να γίνει πρώτα έλεγχος F για τις διακυμάνσεις

#Καθαρισμός περιβάλλοντος
rm(list = ls())

# Ορισμός των απαραίτητων μεταβλητών για το 1ο κατάστημα
sample_size_1 <- 30
sample_mean_1 <- 520
sample_sd_1 <- 50

# Ορισμός των απαραίτητων μεταβλητών για το 2ο κατάστημα
sample_size_2 <- 35
sample_mean_2 <- 490
sample_sd_2 <- 60

# Επίπεδο σημαντικότητας
a <- 0.01

# Υπολογισμός δειγματικών διακυμάνσεων
var_1 <- sample_sd_1^2
var_2 <- sample_sd_2^2

# Υπολογισμός F-statistic για έλεγχο ισότητας διακυμάνσεων
F_stat <- var_1 / var_2

# Βαθμοί ελευθερίας για τον έλεγχο F
df1 <- sample_size_1 - 1
df2 <- sample_size_2 - 1

# Κρίσιμες τιμές F για δίπλευρο έλεγχο
F_lower <- qf(a / 2, df1, df2)
F_upper <- qf(1 - a / 2, df1, df2)

# Εκτύπωση αποτελεσμάτων ελέγχου F
print(paste0("Το F-statistic είναι: ", F_stat))
print(paste0("Η κάτω κρίσιμη τιμή F είναι: ", F_lower))
print(paste0("Η άνω κρίσιμη τιμή F είναι: ", F_upper))

# Έλεγχος αν απορρίπτεται η υπόθεση ίσων διακυμάνσεων
if (F_stat < F_lower | F_stat > F_upper) {
  print("Απορρίπτεται η υπόθεση ίσων διακυμάνσεων.")
  print("Θα πρέπει να χρησιμοποιηθεί ο τύπος για άνισες διακυμάνσεις.")
} else {
  print("Δεν απορρίπτεται η υπόθεση ίσων διακυμάνσεων.")
  print("Χρησιμοποιείται η σταθμισμένη διακύμανση.")
}

# Υπολογισμός σταθμισμένης διακύμανσης
weighted_variance <- ((sample_size_1 - 1) * var_1 + (sample_size_2 - 1) * var_2) / 
                     (sample_size_1 + sample_size_2 - 2)

#Υπολόγισμος t-statistic
t_stat<- (sample_mean_1-sample_mean_2)/sqrt(weighted_variance * (1 / sample_size_1 + 1 / sample_size_2))

# Βαθμοί ελευθερίας για t κατανομή
df <- sample_size_1 + sample_size_2 - 2

# Υπολογισμός κρίσιμων τιμών
left_limit<- a/2
right_limit<- 1-a/2
cr_values<-qt(c(left_limit,right_limit), df)

# Υπολογισμός διαφοράς δειγματικών μέσων
mean_difference <- sample_mean_1 - sample_mean_2

# Υπολογισμός διαστήματος εμπιστοσύνης
interval_99 <- mean_difference +
  cr_values * sqrt(weighted_variance * (1 / sample_size_1 + 1 / sample_size_2))

# Εκτύπωση αποτελεσμάτων διαστήματος εμπιστοσύνης
print(paste0("Η σταθμισμένη διακύμανση είναι: ", weighted_variance))
print(paste0("Η διαφορά των δειγματικών μέσων είναι: ", mean_difference))
print(paste0("Η κάτω κρίσιμη τιμή t είναι: ", cr_values[1]))
print(paste0("Η άνω κρίσιμη τιμή t είναι: ", cr_values[2]))
print(paste0("Το 99% διάστημα εμπιστοσύνης είναι μεταξύ ", interval_99[1], " και ", interval_99[2]))

if (interval_99[1] <= 0 & interval_99[2] >= 0) {
  print("Το διάστημα εμπιστοσύνης περιέχει το 0.")
  print("Δεν υπάρχουν επαρκή στοιχεία για διαφορά μεταξύ των δύο μέσων τιμών.")
} else {
  print("Το διάστημα εμπιστοσύνης δεν περιέχει το 0.")
  print("Υπάρχουν ενδείξεις διαφοράς μεταξύ των δύο μέσων τιμών.")
}



