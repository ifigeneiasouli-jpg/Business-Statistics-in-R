rm(list = ls())

# Ορισμός των απαραίτητων μεταβλητών
sample_size <- 25
sample_var <- 16
a <- 0.05

# Υπολογισμός βαθμών ελευθερίας
df <- sample_size - 1

# Υπολογισμός των κρίσιμων τιμών της χ^2 κατανομής
chi_square_right <- qchisq(1 - a / 2, df)
chi_square_left <- qchisq(a / 2, df)

# Υπολογισμός κάτω ορίου του διαστήματος εμπιστοσύνης
lower_limit <- (df * sample_var) / chi_square_right

# Υπολογισμός άνω ορίου του διαστήματος εμπιστοσύνης
upper_limit <- (df * sample_var) / chi_square_left

