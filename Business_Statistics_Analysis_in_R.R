     xlab = "Τιμές χ^2",
     ylab = "Πυκνότητα πιθανότητας")

# Επιλογή των τιμών που ανήκουν στο κεντρικό 95%
confidence_region <- x_values[x_values >= chi_square_left & x_values <= chi_square_right]
#Κρατάμε μόνο τις τιμές ανάμεσα στις δύο κρίσιμες τιμές

# Υπολογισμός της πυκνότητας στο κεντρικό 95%
confidence_density <- dchisq(confidence_region, df)

# Σκίαση του κεντρικού 95%
polygon(c(chi_square_left, confidence_region, chi_square_right),    #Δίνει τις τιμές στον άξονα x
        c(0, confidence_density, 0),    #Δίνει τις τιμές στον άξονα y
        col = "lightgray")

# Κάθετη γραμμή στην αριστερή κρίσιμη τιμή
abline(v = chi_square_left, lty = 2)

