abline(v = chi_square_right, lty = 2)





#################### Άσκηση 3 ####################
# Έλεγχος υπόθεσης για πληθυσμιακή αναλογία
# Η εταιρεία marketing ισχυρίζεται ότι το ποσοστό ανταπόκρισης είναι 50%
# Χρήση z-test για αναλογία

#Καθαρισμός περιβάλλοντος
rm(list = ls())

# Ορισμός των απαραίτητων μεταβλητών
sample_size <- 200
successes <- 120
null_proportion_value <- 0.50
a <- 0.05

# HO-> p=0.50 και H1-> p<>0.50

# Υπολογισμός της δειγματικής αναλογίας
sample_proportion <- successes / sample_size

# Υπολογισμός του στατιστικού ελέγχου z
z <- (sample_proportion - null_proportion_value) /
  sqrt((null_proportion_value * (1 - null_proportion_value)) / sample_size)

# Υπολογισμός του p-value για δίπλευρο έλεγχο
p_value <- 2 * pnorm(abs(z), lower.tail = FALSE)
#Η pnorm δίνει πιθανότητες από την κανονική κατανομή

# Υπολογισμός κρίσιμης τιμής για δίπλευρο έλεγχο
critical_value <- qnorm(1 - a / 2)
#Η qnorm δίνει κρίσιμες τιμές από την κανονική κατανομή

# Έλεγχος της εναλλακτικής υπόθεσης
print(p_value < a)

# Εκτύπωση αποτελεσμάτων
print(paste0("Η δειγματική αναλογία είναι: ", sample_proportion))
print(paste0("Το z-statistic είναι: ", z))
print(paste0("Η κρίσιμη τιμή είναι: ±", critical_value))
print(paste0("Το p-value είναι: ", p_value))

if (p_value < a) {
  print("Απορρίπτουμε τη μηδενική υπόθεση H0.")
  print("Υπάρχουν επαρκή στοιχεία ότι το ποσοστό ανταπόκρισης είναι διαφορετικό από 50%.")
} else {
  print("Δεν απορρίπτουμε τη μηδενική υπόθεση H0.")
  print("Δεν υπάρχουν επαρκή στοιχεία ότι το ποσοστό ανταπόκρισης είναι διαφορετικό από 50%.")
}



