print(paste0("Οι βαθμοί ελευθερίας είναι: ", df))
print(paste0("Η αριστερή κρίσιμη τιμή χ^2 είναι: ", chi_square_left))
print(paste0("Η δεξιά κρίσιμη τιμή χ^2 είναι: ", chi_square_right))

print(paste0("Το κάτω όριο του 95% διαστήματος εμπιστοσύνης είναι: ", lower_limit))
print(paste0("Το άνω όριο του 95% διαστήματος εμπιστοσύνης είναι: ", upper_limit))

print(paste0("Το 95% διάστημα εμπιστοσύνης για την πληθυσμιακή διακύμανση είναι: [",
             lower_limit, ", ", upper_limit, "]"))



