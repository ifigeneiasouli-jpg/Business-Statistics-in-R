#################### Άσκηση 5  ####################
# Ανάλυση διακύμανσης κατά ένα παράγοντα
# Έλεγχος διαφορών μέσων τιμών ημερήσιας παραγωγής σε τρία εργοστάσια
# Χρήση ANOVA και κατανομής F

#Καθαρισμός περιβάλλοντος
rm(list = ls())

# Ορισμός των δεδομένων
factory_A <- c(20, 22, 19, 24, 23)
factory_B <- c(30, 28, 27, 29, 31)
factory_C <- c(25, 26, 24, 23, 27)
#Με τη c φτιάχνουμε ένα διάνυσμα

# Υπολογισμός δειγματικών μέσων τιμών
x1 <- mean(factory_A)
x2 <- mean(factory_B)
x3 <- mean(factory_C)

# Υπολογισμός δειγματικών διακυμάνσεων
var1 <- var(factory_A)
var2 <- var(factory_B)
var3 <- var(factory_C)

# Υπολογισμός γενικής δειγματικής μέσης τιμής
mean_x <- mean(c(factory_A, factory_B, factory_C))

# Ορισμός επιπέδου σημαντικότητας
a <- 0.01

# Ορισμός πλήθους ομάδων
k <- 3

# Υπολογισμός μεγεθών δείγματος
n1 <- length(factory_A)
n2 <- length(factory_B)
n3 <- length(factory_C)
#Με τη length υπολογίζουμε το μέγεθος του δείγματος ενός διανύσματος

# Υπολογισμός συνολικού μεγέθους δείγματος
n <- n1 + n2 + n3

# Υπολογισμός αθροίσματος τετραγώνων του παράγοντα
SSF <- n1 * (x1 - mean_x)^2 + n2 * (x2 - mean_x)^2 + n3 * (x3 - mean_x)^2

# Υπολογισμός αθροίσματος τετραγώνων του σφάλματος
SSE <- (n1 - 1) * var1 + (n2 - 1) * var2 + (n3 - 1) * var3

# Υπολογισμός μέσου αθροίσματος τετραγώνων του παράγοντα
MSF <- SSF / (k - 1)

# Υπολογισμός μέσου αθροίσματος τετραγώνων του σφάλματος
MSE <- SSE / (n - k)

# Υπολογισμός F-statistic
F_stat <- MSF / MSE

# Υπολογισμός κρίσιμης τιμής F
f_cr <- qf(1 - a, k - 1, n - k)

# Υπολογισμός p-value
p_value <- pf(F_stat, k - 1, n - k, lower.tail = FALSE)
# Η pf() δίνει πιθανότητες από την F κατανομή
