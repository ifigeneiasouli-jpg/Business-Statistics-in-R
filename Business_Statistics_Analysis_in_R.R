#Η χ^2 κατανομή ξεκινά από το 0, γι’ αυτό δε βάζουμε αρνητικές τιμές

# Υπολογισμός τιμών πυκνότητας πιθανότητας της χ^2 κατανομής
y_values <- dchisq(x_values, df)
#Υπολογίζει το ύψος της χ^2 κατανομής σε κάθε τιμή του x_values

# Σχεδίαση της χ^2 κατανομής
plot(x_values, y_values,
